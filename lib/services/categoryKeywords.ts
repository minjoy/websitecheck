/**
 * 키워드에서 가중치 가져오기
 */
export function getKeywordWeight(categoryCode: CategoryCode, keyword: string): number {
  const keywordSet = CATEGORY_KEYWORD_MAP[categoryCode];
  if (!keywordSet) return 0;

  if (keywordSet.core.includes(keyword)) {
    return 2.0; // 핵심 키워드
  }
  if (keywordSet.secondary.includes(keyword)) {
    return 1.0; // 보조 키워드
  }
  return 0;
}

/**
 * 모든 카테고리의 모든 키워드를 평탄화한 Set 반환
 */
export function getAllKeywords(): Set<string> {
  const allKeywords = new Set<string>();
  Object.values(CATEGORY_KEYWORD_MAP).forEach(keywordSet => {
    keywordSet.core.forEach(kw => allKeywords.add(kw));
    keywordSet.secondary.forEach(kw => allKeywords.add(kw));
  });
  return allKeywords;
}
